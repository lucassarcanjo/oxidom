//! Build script: generates every table that both the Rust core and the JS facade depend on, from the
//! same data, so the two sides cannot drift.
//!
//! Inputs (all committed):
//! - `data/atoms/*.txt`        static atoms (concatenated in file-name order, de-duplicated)
//! - `data/events.txt`         event names; each also yields an `on<name>` atom
//! - `data/role-selectors.txt` aria-query role selectors; their tag and attribute names become atoms
//! - `data/interfaces.json`    tag -> interface table (regenerate with `node scripts/gen-interfaces.mjs`)
//! - `data/css/properties.tsv` CSS property table (also `include_str!`ed by `src/style/props.rs`)
//! - `src/**/*.rs`             `natives! { ... }` blocks (per-module native function lists)
//!
//! Outputs:
//! - `$OUT_DIR/atoms.rs`        `STATIC_ATOMS`, `STATIC_TABLE` (hash table over `src/atom_hash.rs`), `atom::*`
//! - `$OUT_DIR/natives.rs`      `REGISTRY`: every module's `NATIVES` slice (no hand-edited central list)
//!
//! JS outputs go to the npm package (`packages/rsdom/lib/generated/`, gitignored; override the directory
//! with `RSDOM_JS_GENERATED_DIR`):
//! - `atoms.cjs`                static atom names (index = atom id)
//! - `interfaces.cjs`, `events.cjs`
//! - `css-properties.cjs`       CSS property names (index = property id, `data/css/properties.tsv` order)
//! - `native.d.ts`              typings for every registered native function
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

#[path = "src/atom_hash.rs"]
#[allow(dead_code)]
mod atom_hash;

fn main() {
    napi_build::setup();
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=data");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=build.rs");

    let atoms = collect_atoms(&root);
    write_atoms_rs(&atoms, &out_dir.join("atoms.rs"));
    println!("cargo:rerun-if-env-changed=RSDOM_JS_GENERATED_DIR");
    let gen_dir = match std::env::var_os("RSDOM_JS_GENERATED_DIR") {
        Some(dir) => PathBuf::from(dir),
        None => root.join("../../packages/rsdom/lib/generated"),
    };
    fs::create_dir_all(&gen_dir).unwrap();
    write_atoms_cjs(&atoms, &gen_dir.join("atoms.cjs"));

    let interfaces = fs::read_to_string(root.join("data/interfaces.json")).expect("data/interfaces.json");
    write_if_changed(
        &gen_dir.join("interfaces.cjs"),
        &format!(
            "// @generated by build.rs from data/interfaces.json. Do not edit.\n'use strict';\nmodule.exports = {};\n",
            interfaces.trim()
        ),
    );
    let events = read_list(&root.join("data/events.txt"));
    let mut ev = String::from(
        "// @generated by build.rs from data/events.txt. Do not edit.\n'use strict';\nmodule.exports = [\n",
    );
    for (name, _) in &events {
        writeln!(ev, "  {name:?},").unwrap();
    }
    ev.push_str("];\n");
    write_if_changed(&gen_dir.join("events.cjs"), &ev);

    let props = fs::read_to_string(root.join("data/css/properties.tsv")).expect("data/css/properties.tsv");
    let mut css = String::from(
        "// @generated by build.rs from data/css/properties.tsv. Do not edit.\n'use strict';\n\
         /** CSS property names, index = property id. */\nmodule.exports = [\n",
    );
    for line in props.lines().filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let name = line.split('\t').next().unwrap();
        writeln!(css, "  {name:?},").unwrap();
    }
    css.push_str("];\n");
    write_if_changed(&gen_dir.join("css-properties.cjs"), &css);

    let natives = collect_natives(&root.join("src"));
    write_registry(&natives, &out_dir.join("natives.rs"));
    write_dts(&natives, &gen_dir.join("native.d.ts"));
}

// ------------------------------------------------------------------------------------------------ atoms

/// (name, optional explicit constant name)
fn read_list(path: &Path) -> Vec<(String, Option<String>)> {
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        // Comments are `#` followed by a space (or a bare `#`); `#text`-style names are atoms.
        if line.is_empty() || line == "#" || line.starts_with("# ") {
            continue;
        }
        match line.split_once(" = ") {
            Some((n, c)) => out.push((n.trim().to_string(), Some(c.trim().to_string()))),
            None => out.push((line.to_string(), None)),
        }
    }
    out
}

fn collect_atoms(root: &Path) -> Vec<(String, String)> {
    let mut files: Vec<PathBuf> = fs::read_dir(root.join("data/atoms"))
        .expect("data/atoms")
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "txt"))
        .collect();
    files.sort();
    let mut raw: Vec<(String, Option<String>)> = Vec::new();
    for f in &files {
        raw.extend(read_list(f));
    }
    for (ev, _) in read_list(&root.join("data/events.txt")) {
        raw.push((format!("on{ev}"), None));
        raw.push((ev, None));
    }
    // Tag and attribute names used by the aria-query role selectors.
    let sel = fs::read_to_string(root.join("data/role-selectors.txt")).expect("data/role-selectors.txt");
    for line in sel.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let tag: String = line.chars().take_while(|c| c.is_ascii_alphanumeric()).collect();
        if !tag.is_empty() {
            raw.push((tag, None));
        }
        let mut rest = line;
        while let Some(i) = rest.find('[') {
            rest = &rest[i + 1..];
            let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '-').collect();
            if !name.is_empty() {
                raw.push((name, None));
            }
        }
    }

    let mut seen = HashSet::new();
    let mut consts = HashSet::new();
    let mut out = Vec::new();
    for (name, explicit) in raw {
        if !seen.insert(name.clone()) {
            continue;
        }
        let c = explicit.unwrap_or_else(|| const_name(&name));
        assert!(
            consts.insert(c.clone()),
            "atom constant name collision: {c} (from {name:?}); add an explicit ` = NAME`"
        );
        out.push((name, c));
    }
    out
}

/// `foreignObject` -> `FOREIGN_OBJECT`, `aria-label` -> `ARIA_LABEL`, `xlink:href` -> `XLINK_HREF`,
/// `#text` -> `HASH_TEXT`, `http://www.w3.org/1999/xhtml` -> `NS_HTML` (well-known URIs).
fn const_name(name: &str) -> String {
    match name {
        "http://www.w3.org/1999/xhtml" => return "NS_HTML".into(),
        "http://www.w3.org/2000/svg" => return "NS_SVG".into(),
        "http://www.w3.org/1998/Math/MathML" => return "NS_MATHML".into(),
        "http://www.w3.org/1999/xlink" => return "NS_XLINK".into(),
        "http://www.w3.org/XML/1998/namespace" => return "NS_XML".into(),
        "http://www.w3.org/2000/xmlns/" => return "NS_XMLNS".into(),
        _ => {}
    }
    let mut s = String::new();
    let mut prev_lower = false;
    for ch in name.chars() {
        if ch == '#' {
            s.push_str("HASH_");
            prev_lower = false;
        } else if ch.is_ascii_uppercase() {
            if prev_lower {
                s.push('_');
            }
            s.push(ch);
            prev_lower = false;
        } else if ch.is_ascii_alphanumeric() {
            s.push(ch.to_ascii_uppercase());
            prev_lower = ch.is_ascii_lowercase() || ch.is_ascii_digit();
        } else {
            s.push('_');
            prev_lower = false;
        }
    }
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}

fn write_atoms_rs(atoms: &[(String, String)], path: &Path) {
    let mut s = String::from("// @generated by build.rs\n");
    writeln!(s, "/// Number of static atoms including the reserved id 0.").unwrap();
    writeln!(s, "pub const STATIC_LEN: u32 = {};", atoms.len() + 1).unwrap();
    writeln!(s, "/// Static atom names; index = atom id (0 = none).").unwrap();
    writeln!(s, "pub static STATIC_ATOMS: [&str; {}] = [\"\",", atoms.len() + 1).unwrap();
    for (n, _) in atoms {
        writeln!(s, "    {n:?},").unwrap();
    }
    s.push_str("];\n");
    // Static atom table: open addressing (linear probing) over `atom_hash`, load factor <= 1/4, so most
    // lookups hit the home slot. The runtime probes it with the same hash it uses for dynamic atoms.
    let bits = ((atoms.len() * 4).next_power_of_two().trailing_zeros()).max(4);
    let size = 1usize << bits;
    let mut table = vec![0u32; size];
    for (i, (n, _)) in atoms.iter().enumerate() {
        let mut p = atom_hash::slot(atom_hash::atom_hash(n.as_bytes()), bits);
        while table[p] != 0 {
            p = (p + 1) & (size - 1);
        }
        table[p] = (i + 1) as u32;
    }
    assert!(atoms.len() < u16::MAX as usize, "static atoms must fit u16 slots");
    writeln!(
        s,
        "/// High 32 bits of each static atom's hash (index = atom id): probes skip the string compare."
    )
    .unwrap();
    write!(s, "pub static STATIC_FP: [u32; {}] = [0,", atoms.len() + 1).unwrap();
    for (i, (n, _)) in atoms.iter().enumerate() {
        if i % 16 == 0 {
            s.push_str("\n   ");
        }
        write!(s, " {},", (atom_hash::atom_hash(n.as_bytes()) >> 32) as u32).unwrap();
    }
    s.push_str("\n];\n");
    writeln!(s, "/// log2 of the static atom table size.").unwrap();
    writeln!(s, "pub const STATIC_BITS: u32 = {bits};").unwrap();
    writeln!(s, "/// Static atom table (open addressing over `atom_hash`; 0 = empty slot).").unwrap();
    write!(s, "pub static STATIC_TABLE: [u16; {size}] = [").unwrap();
    for (i, v) in table.iter().enumerate() {
        if i % 32 == 0 {
            s.push_str("\n   ");
        }
        write!(s, " {v},").unwrap();
    }
    s.push_str("\n];\n");
    s.push_str("/// Compile-time atom constants (`atom::DIV`, `atom::ARIA_LABEL`, `atom::NS_SVG`, ...).\n");
    s.push_str("#[allow(dead_code, missing_docs)]\npub mod atom {\n    use super::Atom;\n");
    for (i, (n, c)) in atoms.iter().enumerate() {
        writeln!(s, "    /// `{}`", n.replace('`', "'")).unwrap();
        writeln!(s, "    pub const {c}: Atom = Atom({});", i + 1).unwrap();
    }
    s.push_str("}\n");
    fs::write(path, s).unwrap();
}

fn write_atoms_cjs(atoms: &[(String, String)], path: &Path) {
    let mut joined = String::new();
    for (n, _) in atoms {
        joined.push('\0');
        joined.push_str(n);
    }
    let s = format!(
        "// @generated by build.rs from data/atoms, data/events.txt, data/role-selectors.txt. Do not edit.\n\
         'use strict';\n/** Static atom names, index = atom id (0 = none). */\nmodule.exports = {:?}.split('\\0');\n",
        joined
    )
    .replace("\\u{0}", "\\0");
    write_if_changed(path, &s);
}

// ---------------------------------------------------------------------------------------------- natives

struct NativeDecl {
    module: String,
    name: String,
    params: Vec<(String, String)>,
    ret: String,
    docs: Vec<String>,
    file: String,
}

fn collect_natives(src: &Path) -> Vec<NativeDecl> {
    let mut files = Vec::new();
    walk(src, &mut files);
    files.sort();
    let mut out = Vec::new();
    for f in files {
        let text = fs::read_to_string(&f).unwrap();
        let rel = f.strip_prefix(src).unwrap().to_string_lossy().replace('\\', "/");
        let module = module_path(&rel);
        let mut in_block = false;
        let mut docs = Vec::new();
        for line in text.lines() {
            if !in_block {
                if line.trim_start().starts_with("natives! {") {
                    in_block = true;
                }
                continue;
            }
            if line == "}" {
                in_block = false;
                continue;
            }
            let t = line.trim();
            if let Some(d) = t.strip_prefix("///") {
                docs.push(d.trim().to_string());
                continue;
            }
            if let Some(rest) = t.strip_prefix("fn ") {
                let (name, rest) =
                    rest.split_once('(').unwrap_or_else(|| panic!("{rel}: bad native header: {t}"));
                let (params, rest) =
                    rest.split_once(')').unwrap_or_else(|| panic!("{rel}: bad native header: {t}"));
                let ret = rest
                    .trim()
                    .strip_prefix("->")
                    .unwrap_or_else(|| panic!("{rel}: native `{name}` needs an explicit `-> Type`"))
                    .trim()
                    .trim_end_matches('{')
                    .trim()
                    .to_string();
                let params = params
                    .split(',')
                    .skip(1) // the Env binding
                    .filter(|p| !p.trim().is_empty())
                    .map(|p| {
                        let (n, ty) = p.split_once(':').unwrap_or_else(|| panic!("{rel}: bad param {p}"));
                        (n.trim().to_string(), ty.trim().to_string())
                    })
                    .collect();
                out.push(NativeDecl {
                    module: module.clone(),
                    name: name.trim().to_string(),
                    params,
                    ret,
                    docs: std::mem::take(&mut docs),
                    file: rel.clone(),
                });
            } else if !t.is_empty() && !t.starts_with("//") {
                docs.clear();
            }
        }
    }
    let mut seen = BTreeMap::new();
    for n in &out {
        if let Some(prev) = seen.insert(n.name.clone(), n.file.clone()) {
            panic!("native `{}` defined twice ({} and {})", n.name, prev, n.file);
        }
    }
    out
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    for e in fs::read_dir(dir).unwrap() {
        let p = e.unwrap().path();
        if p.is_dir() {
            walk(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
}

fn module_path(rel: &str) -> String {
    let rel = rel.trim_end_matches(".rs");
    let rel = rel.trim_end_matches("/mod");
    if rel == "lib" { "crate".to_string() } else { format!("crate::{}", rel.replace('/', "::")) }
}

fn write_registry(natives: &[NativeDecl], path: &Path) {
    let mut modules: Vec<&str> = natives.iter().map(|n| n.module.as_str()).collect();
    modules.dedup();
    let mut s = String::from("// @generated by build.rs: every module that contains a `natives!` block.\n");
    writeln!(s, "pub(crate) static REGISTRY: &[&[crate::ffi::Native]] = &[").unwrap();
    for m in &modules {
        writeln!(s, "    {m}::NATIVES,").unwrap();
    }
    s.push_str("];\n");
    writeln!(s, "/// Total number of registered natives (checked against the registry in tests).").unwrap();
    writeln!(s, "#[allow(dead_code)]\npub(crate) const NATIVE_COUNT: usize = {};", natives.len()).unwrap();
    fs::write(path, s).unwrap();
}

fn ts_param(ty: &str) -> &'static str {
    match ty {
        "u32" | "i32" | "f64" => "number",
        "bool" => "boolean",
        "str" => "string",
        "ostr" => "string | null",
        "buf" => "ArrayBuffer",
        "any" => "unknown",
        other => panic!("unknown native param type `{other}` (use u32/i32/f64/bool/str/ostr/buf/any)"),
    }
}

fn ts_ret(ty: &str) -> &'static str {
    match ty.replace(' ', "").as_str() {
        "u32" | "i32" | "f64" | "Code" | "NodeId" | "Atom" => "number",
        "bool" => "boolean",
        "&str" | "&Str" => "string",
        "Option<&str>" | "Option<&Str>" => "string | null",
        "()" => "undefined",
        "Value" => "unknown",
        "TableBuf" => "ArrayBuffer | null",
        other => panic!("unknown native return type `{other}`"),
    }
}

fn write_dts(natives: &[NativeDecl], path: &Path) {
    let mut s = String::from(
        "// @generated by build.rs from the `natives!` blocks in src/. Do not edit.\n\
         // Raw Node-API callbacks: arguments must already be coerced by the facade (u32, boolean, string).\n\
         // Ids are node ids (0 = null); `a` = atom id; error codes: see src/error.rs.\n\
         export interface Native {\n",
    );
    let mut last_file = "";
    for n in natives {
        if n.file != last_file {
            writeln!(s, "  // ---- src/{}", n.file).unwrap();
            last_file = &n.file;
        }
        if !n.docs.is_empty() {
            writeln!(s, "  /** {} */", n.docs.join(" ").replace("*/", "* /")).unwrap();
        }
        let params: Vec<String> = n.params.iter().map(|(p, t)| format!("{p}: {}", ts_param(t))).collect();
        writeln!(s, "  {}({}): {};", n.name, params.join(", "), ts_ret(&n.ret)).unwrap();
    }
    s.push_str("}\ndeclare const native: Native;\nexport default native;\n");
    write_if_changed(path, &s);
}

fn write_if_changed(path: &Path, content: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        fs::write(path, content).unwrap();
    }
}
