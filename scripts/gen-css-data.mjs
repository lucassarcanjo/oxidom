#!/usr/bin/env node
// Regenerates the CSS data rsdom vendors from jsdom 30.1.3 (a devDependency of packages/rsdom):
//   crates/rsdom/data/css/properties.tsv  every CSS property jsdom knows (lib/generated/css-property-definitions.js
//                                    + css-property-metadata.js): name, inherited, initial value, value-type
//                                    flags, longhands. The id of a property is its line index (0-based, after
//                                    the header comments); Rust (src/style/props.rs) reads this file and
//                                    build.rs turns it into lib/generated/css-properties.cjs for the facade
//                                    (packages/rsdom/lib/style.cjs), so they cannot drift.
//   crates/rsdom/data/css/default-stylesheet.css  jsdom's UA stylesheet (lib/jsdom/browser/default-stylesheet.css), the
//                                    first level of rsdom's cascade (DESIGN §8.2).
// The outputs are committed (hermetic builds). Run: `node scripts/gen-css-data.mjs`.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const jsdomRoot = path.dirname(require.resolve('jsdom/package.json'));
const version = require('jsdom/package.json').version;
const gen = path.join(jsdomRoot, 'lib/generated');
const defs = require(path.join(gen, 'css-property-definitions.js'));
const meta = require(path.join(gen, 'css-property-metadata.js'));
const out = path.resolve(here, '../crates/rsdom/data/css');
fs.mkdirSync(out, { recursive: true });

/** Value-type flags (mirrored in src/style/props.rs `flag`). */
const F = {
  CASE_SENSITIVE: 1, LENGTH: 2, LENGTH_NONNEG: 4, NUMBER: 8, NUMBER_NONNEG: 16, NUMBER_MIN1: 32,
  PERCENT: 64, PERCENT_NONNEG: 128, DIMENSION: 256, DIMENSION_NONNEG: 512, COLOR: 1024, IMAGE: 2048,
  PAINT: 4096, ANGLE: 8192, RATIO: 16384,
};

function flagsOf(m) {
  if (!m) return 0;
  let f = m.caseSensitive ? F.CASE_SENSITIVE : 0;
  const d = m.dimensionTypes ?? {};
  const nonneg = (t) => t.min === 0 || t.min === '0s' || t.min === '0';
  if (d.length) f |= F.LENGTH | (nonneg(d.length) ? F.LENGTH_NONNEG : 0);
  if (d.number) f |= F.NUMBER | (d.number.min === 0 ? F.NUMBER_NONNEG : 0) | (d.number.min === 1 ? F.NUMBER_MIN1 : 0);
  if (d.percentage) f |= F.PERCENT | (nonneg(d.percentage) ? F.PERCENT_NONNEG : 0);
  if (d.dimension) f |= F.DIMENSION | (nonneg(d.dimension) ? F.DIMENSION_NONNEG : 0);
  if (d.angle) f |= F.ANGLE;
  if (d.ratio) f |= F.RATIO;
  const fn = m.functionTypes ?? {};
  if (fn.color) f |= F.COLOR;
  if (fn.image) f |= F.IMAGE;
  if (fn.paint) f |= F.PAINT;
  return f;
}

const clean = (s) => String(s ?? '').replace(/[\t\n]/g, ' ');
const lines = [
  `# @generated by scripts/gen-css-data.mjs from jsdom ${version} (lib/generated/css-property-*.js). Do not edit.`,
  '# name<TAB>inherited(0/1)<TAB>initial<TAB>flags<TAB>longhands(comma-separated). Property id = data line index.',
];
for (const [name, d] of defs) {
  lines.push([name, d.inherited === 'yes' ? 1 : 0, clean(d.initial), flagsOf(meta.get(name)), (d.longhands ?? []).join(',')].join('\t'));
}
fs.writeFileSync(path.join(out, 'properties.tsv'), lines.join('\n') + '\n');

const ua = fs.readFileSync(path.join(jsdomRoot, 'lib/jsdom/browser/default-stylesheet.css'), 'utf8');
fs.writeFileSync(
  path.join(out, 'default-stylesheet.css'),
  `/* @generated by scripts/gen-css-data.mjs: jsdom ${version} lib/jsdom/browser/default-stylesheet.css (MIT). Do not edit. */\n${ua}`,
);
console.log(`wrote ${defs.size} properties and the UA stylesheet (${ua.length} bytes) to ${out}`);
