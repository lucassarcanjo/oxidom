// Parity scoreboard (results/summary.md), computed from committed files only: the jsdom oracle
// (oracle/<source>.json: what jsdom passes in this harness), oxidom's expectations (expectations/<source>.yaml)
// and the roadmap scopes (roadmap.yaml). `run.mjs --update` calls it; `node report.mjs` regenerates it.
//
// Score: of the subtests jsdom passes, how many oxidom passes. Per file:
//   no oxidom entry            -> oxidom passes all of them
//   subtest list X            -> oxidom misses the members of X that jsdom passes
//   file entry, floor p       -> oxidom misses max(0, jsdom passes - p)   (assumes oxidom's passes are among jsdom's)
//   `skip` entry              -> left out (the file does not measure oxidom)
// An item's main causes are the reasons of its files' gaps.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCES, RESULTS, REFERENCE_NODE, loadExpectations, loadOracle, loadRoadmap } from './lib.mjs';

function fileGap(o, e) {
  const jsdomPass = o.pass;
  if (!e) return { jsdomPass, gap: 0, reasons: [] };
  if (e.subtests) {
    const jf = new Set(o.fail);
    const reasons = new Map();
    let gap = 0;
    for (const [name, reason] of e.subtests) {
      if (jf.has(name)) continue;
      gap++;
      reasons.set(reason, (reasons.get(reason) ?? 0) + 1);
    }
    // capped: where jsdom passes nothing the oracle keeps no failure names, so none were subtracted above
    const capped = Math.min(gap, jsdomPass);
    return { jsdomPass, gap: capped, reasons: capped ? [...reasons] : [] };
  }
  const gap = Math.max(0, jsdomPass - (e.pass ?? 0));
  return { jsdomPass, gap, reasons: gap ? [[e.reason, gap]] : [] };
}

const pct = (a, b) => (b ? `${((100 * a) / b).toFixed(1)}%` : '–');
const esc = (s) => String(s).replace(/\|/g, '\\|');

export function computeReport() {
  const roadmap = loadRoadmap();
  const perSource = [];
  const files = []; // { source, id, jsdomPass, gap, reasons }
  const keys = []; // every `<source>:<id>`, for the roadmap glob check
  for (const source of Object.keys(SOURCES)) {
    const oracle = loadOracle(source);
    if (!oracle.size) continue;
    const exps = loadExpectations(source, REFERENCE_NODE);
    const tot = { source, files: 0, jsdomPass: 0, gap: 0, atParity: 0, fullyPassing: 0, entries: exps.size };
    for (const [id, o] of oracle) {
      keys.push(`${source}:${id}`);
      if (exps.get(id)?.status === 'skip') continue;
      const g = fileGap(o, exps.get(id));
      files.push({ source, id, ...g });
      tot.files++;
      tot.jsdomPass += g.jsdomPass;
      tot.gap += g.gap;
      if (g.gap === 0) tot.atParity++;
      if (!exps.has(id)) tot.fullyPassing++;
    }
    perSource.push(tot);
  }
  for (const it of roadmap) {
    for (const g of it.include) if (!keys.some((k) => path.matchesGlob(k, g))) console.warn(`parity: roadmap.yaml: ${it.id}: '${g}' matches no test`);
  }
  const items = roadmap.map((it) => {
    const mine = files.filter((f) => it.match(f.source, f.id));
    const reasons = new Map();
    for (const f of mine) for (const [r, n] of f.reasons) reasons.set(r, (reasons.get(r) ?? 0) + n);
    return {
      ...it,
      files: mine.length,
      jsdomPass: mine.reduce((a, f) => a + f.jsdomPass, 0),
      gap: mine.reduce((a, f) => a + f.gap, 0),
      atParity: mine.filter((f) => f.gap === 0).length,
      top: [...reasons].sort((a, b) => b[1] - a[1]).slice(0, 3),
    };
  });
  const unmapped = new Map();
  for (const f of files) {
    if (!f.gap || roadmap.some((it) => it.match(f.source, f.id))) continue;
    const dir = `${f.source}:${f.id.split('/').slice(0, f.source === 'wpt' || f.source === 'tuwpt' ? 2 : 1).join('/')}`;
    const u = unmapped.get(dir) ?? { files: 0, gap: 0 };
    u.files++;
    u.gap += f.gap;
    unmapped.set(dir, u);
  }
  return { perSource, items, unmapped: [...unmapped].sort((a, b) => b[1].gap - a[1].gap) };
}

export function renderReport({ perSource, items, unmapped }) {
  const L = [];
  L.push('# oxidom parity with jsdom: scoreboard', '');
  L.push('Generated by `node conformance/parity/report.mjs` (also run by `npm run test:parity -- --update`) from the jsdom');
  L.push('oracle and oxidom\'s expectations. **Parity** = of the subtests jsdom passes in this harness, the share oxidom');
  L.push('passes. **Files at parity** = files where oxidom passes everything jsdom passes. Files marked `skip` in the');
  L.push('expectations are left out. Method: `../README.md`.', '');
  L.push('## By source', '');
  L.push('| source | files | files at parity | jsdom-passing subtests | oxidom passes | parity |');
  L.push('| --- | ---: | ---: | ---: | ---: | ---: |');
  let F = 0;
  let P = 0;
  let J = 0;
  let G = 0;
  for (const s of perSource) {
    L.push(`| ${SOURCES[s.source].title} | ${s.files} | ${s.atParity} | ${s.jsdomPass} | ${s.jsdomPass - s.gap} | ${pct(s.jsdomPass - s.gap, s.jsdomPass)} |`);
    F += s.files;
    P += s.atParity;
    J += s.jsdomPass;
    G += s.gap;
  }
  L.push(`| **all** | **${F}** | **${P}** | **${J}** | **${J - G}** | **${pct(J - G, J)}** |`, '');
  L.push('## By roadmap item (docs/ROADMAP.md)', '');
  L.push('Scopes are in `roadmap.yaml`; an item is done when its gap is 0 (or every remaining entry is explained).', '');
  L.push('| stage | item | files | files at parity | gap (subtests) | parity | main causes |');
  L.push('| --- | --- | ---: | ---: | ---: | ---: | --- |');
  for (const it of items) {
    const causes = it.top.map(([r, n]) => `${esc(r)} (${n})`).join('; ');
    L.push(`| ${it.stage} | ${esc(it.title)} | ${it.files || '–'} | ${it.files ? it.atParity : '–'} | ${it.files ? it.gap : '–'} | ${it.files ? pct(it.jsdomPass - it.gap, it.jsdomPass) : 'no tests selected'} | ${causes} |`);
  }
  L.push('', '## Gaps outside every roadmap item', '');
  L.push('Directories where oxidom misses subtests jsdom passes and no roadmap item claims the files.', '');
  L.push('| directory | files with a gap | gap (subtests) |', '| --- | ---: | ---: |');
  for (const [dir, u] of unmapped.slice(0, 40)) L.push(`| ${dir} | ${u.files} | ${u.gap} |`);
  if (unmapped.length > 40) L.push(`| … ${unmapped.length - 40} more | | |`);
  return L.join('\n') + '\n';
}

export function writeReport() {
  const md = renderReport(computeReport());
  fs.mkdirSync(RESULTS, { recursive: true });
  fs.writeFileSync(path.join(RESULTS, 'summary.md'), md);
  return md;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(writeReport());
